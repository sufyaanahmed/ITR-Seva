/**
 * Generate the two agent-discovery documents Vite serves from `public/`.
 *
 * The route, field, lifecycle and finder registries remain the source of
 * truth. Keeping this deterministic means `npm run build` does not introduce
 * timestamp-only diffs.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { ROUTES, REDIRECTS, SITE_NAME } from '../src/lib/routes.js';
import { STAGES, allFields, requiredDocuments } from '../src/lib/fields.js';
import { STATES, STATE_META } from '../src/lib/application.js';
import { QUESTIONS, RULESET_VERSION } from '../src/lib/rules/index.js';
import { SOURCE_LIST, REVIEWED_AT } from '../src/lib/rules/sources.js';

const here = dirname(fileURLToPath(import.meta.url));
const publicDir = resolve(here, '../public');
const generatedNotice = '<!-- Generated by scripts/generate-agent-docs.mjs. Do not edit by hand. -->';
const actions = [...new Set(ROUTES.flatMap((route) => route.agentActions ?? []))].sort();

const escapeCell = (value) => String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
const table = (headers, rows) => [
  `| ${headers.join(' | ')} |`,
  `| ${headers.map(() => '---').join(' | ')} |`,
  ...rows.map((row) => `| ${row.map(escapeCell).join(' | ')} |`),
].join('\n');

const routeRows = ROUTES.map((route) => [
  `\`${route.path}\``, route.title, route.group, route.description,
  (route.agentActions ?? []).map((action) => `\`${action}\``).join(', ') || 'Read-only',
]);

const stageRows = STAGES.map((stage) => [
  `\`${stage.id}\``, stage.title, stage.purpose, stage.effort,
  stage.groups.flatMap((group) => group.fields).length,
]);

const fieldRows = allFields().map((field) => [
  `\`${field.name}\``, field.label, field.type, field.required ? 'Yes' : 'No',
  field.sensitivity ?? 'none',
]);

const questionRows = QUESTIONS.map((question) => [
  `\`${question.id}\``, question.legend ?? question.question ?? question.label ?? question.title,
  (question.options ?? []).map((option) => `${option.value}: ${option.label}`).join('; '),
]);

const stateRows = STATES.map((state) => [
  `\`${state}\``, STATE_META[state].label, STATE_META[state].note ?? '',
]);

const sourceRows = SOURCE_LIST.map((source) => [
  source.title, source.url, source.reviewedAt ?? REVIEWED_AT,
]);

const agent = `${generatedNotice}
# ${SITE_NAME}: agent interface

${SITE_NAME} is an independent fictional prototype for planning and practising an Indian visa journey. It is not an official Government of India service. Never enter real passport, payment, identity, or document data. It does not submit applications or collect payments.

## Safety and commitment boundaries

- Treat every record and outcome as fictional demonstration data.
- Finder results are conservative guidance, not an eligibility decision.
- A person must explicitly confirm simulated payment, submission, document selection, document resubmission, and clearing saved demo data.
- Do not bypass confirmation controls, infer missing sensitive values, or upload real files.
- Prefer the official source linked by an outcome when authoritative confirmation is needed.

## Route registry

${table(['Route', 'Page', 'Group', 'Purpose', 'Agent actions'], routeRows)}

Legacy redirects: ${REDIRECTS.map(({ from, to }) => `\`${from}\` → \`${to}\``).join(', ')}.

## Discoverable actions

${actions.map((action) => `- \`${action}\``).join('\n')}

Only use an action when it is exposed by the current route and application state. Lifecycle controls are state-dependent.

## Application stages

${table(['ID', 'Stage', 'Purpose', 'Typical effort', 'Fields'], stageRows)}

## Lifecycle states

${table(['State', 'Human label', 'Meaning'], stateRows)}

An application starts as \`DRAFT\`. Review is allowed only when required visible fields and required demo documents are present. Submission and simulated payment require a person’s explicit confirmation. Submitted records are not editable. Status and timelines derive from the same application record.

## Fields

Field IDs in the DOM are generated as \`field-<hyphenated-name>\`. Requiredness can depend on earlier answers; use the rendered field’s semantics as authoritative for the current state.

${table(['Name', 'Label', 'Control', 'Required', 'Sensitivity'], fieldRows)}

Required demo-document slots currently defined by the schema: ${requiredDocuments({ application_type: 'evisa', visa_category: 'tourist' }).map((doc) => `\`${doc.type}\``).join(', ')}. Only filenames and metadata are stored; file contents are not persisted.

## Visa Finder schema

Ruleset version: \`${RULESET_VERSION}\`. Sources reviewed: \`${REVIEWED_AT}\`.

${table(['Answer key', 'Question', 'Permitted values'], questionRows)}

Finder outcomes can be \`LIKELY_PATH\`, \`NEEDS_OFFICIAL_REVIEW\`, \`NOT_AVAILABLE_ONLINE\`, or \`INSUFFICIENT_INFORMATION\`. Do not convert “likely path” into “eligible”, “approved”, or “guaranteed”.

## Official source register

${table(['Source', 'URL', 'Reviewed'], sourceRows)}

## Persistence contract

The active demo application is saved to this browser’s local storage. Preferences are stored separately and survive “Clear demo data”. Save status in the interface is authoritative: never claim a save completed merely because a field was edited. A stable fictional application ID plus fictional access code connects start, resume, tracking, status, documents, print, and before-travel guidance.
`;

const llms = `# ${SITE_NAME}

> Independent fictional prototype; not an official Government of India service. Never use real personal, passport, payment, or document data.

## Primary tasks
${ROUTES.filter((route) => route.nav?.includes('header')).map((route) => {
  const examplePath = route.path.replace(':step', '1').replaceAll(/:[^/]+/g, 'example');
  return `- [${route.title}](${examplePath}): ${route.description}`;
}).join('\n')}

## Reviewer entry point
- [Demo scenarios](/demo): deterministic records for draft, processing, documents-required, granted, and refused states.

## Agent documentation
- [Complete agent interface](/agent.md): routes, actions, fields, state model, finder inputs, safety boundaries, and official sources.

Ruleset ${RULESET_VERSION}; official sources reviewed ${REVIEWED_AT}.
`;

await mkdir(publicDir, { recursive: true });
await Promise.all([
  writeFile(resolve(publicDir, 'agent.md'), agent, 'utf8'),
  writeFile(resolve(publicDir, 'llms.txt'), llms, 'utf8'),
]);

process.stdout.write(`Generated public/agent.md and public/llms.txt from ${ROUTES.length} routes, ${allFields().length} fields, and ${STATES.length} states.\n`);
